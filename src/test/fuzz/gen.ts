// 失敗時に、縮小した反例だけを短く報告する
export const assertProperty = async (property: Parameters<typeof fc.check>[0], numRuns: number) => {
  const result = await fc.check(property, { numRuns });
  if (result.failed) {
    throw new Error(
      `FAILED after ${String(result.numRuns)} runs, shrunk ${String(result.numShrinks)}, seed ${String(result.seed)}\nCOUNTEREXAMPLE: ${JSON.stringify(result.counterexample)}\nERROR: ${((result.errorInstance as Error).stack ?? String(result.errorInstance)).slice(0, 700)}`
    );
  }
  return result.numRuns;
};
