export const mutated = fc.tuple(markdown, fc.array(fc.tuple(fc.nat(2000), uni), { maxLength: 3 })).map(([s, edits]) => {
  let out = s;
  for (const [pos, ch] of edits) {
    const p = pos % (out.length + 1);
    out = out.slice(0, p) + ch + out.slice(p);
  }
  return out;
});

